/**
 * Get state details by GST state code (e.g., '27')
 */
export const getStateByCode = (code) => {
  if (!code) return null;
  const cleanCode = String(code).trim().padStart(2, '0');
  return INDIAN_STATES.find((s) => s.code === cleanCode) || null;
};

/**
 * Get state details by name (case-insensitive)
 */
export const getStateByName = (name) => {
  if (!name) return null;
  const cleanName = String(name).trim().toLowerCase();
  return (
    INDIAN_STATES.find(
      (s) => s.name.toLowerCase() === cleanName || s.name.toLowerCase().includes(cleanName)
    ) || null
  );
};

/**
 * Get cities list for a given state name or code
 */
export const getCitiesForState = (stateNameOrCode) => {
  if (!stateNameOrCode) return [];
  const stateObj =
    getStateByCode(stateNameOrCode) || getStateByName(stateNameOrCode);
  return stateObj ? stateObj.cities : [];
};

/**
 * Get 2-digit GST state code for a given state name
 */
export const getStateCode = (stateName) => {
  const stateObj = getStateByName(stateName);
  return stateObj ? stateObj.code : '27';
};
